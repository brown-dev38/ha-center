let stepCursor = 0

function run(text, opts = {}) {
  return new TextRun({
    text,
    font: FONT,
    size: opts.size ?? 22,
    bold: opts.bold,
    color: opts.color,
    italics: opts.italics,
  })
}

function p(text, opts = {}) {
  return new Paragraph({
    spacing: { before: opts.before ?? 80, after: opts.after ?? 80, line: 276 },
    alignment: opts.align,
    children: [run(text, opts)],
  })
}

function rich(parts, opts = {}) {
  return new Paragraph({
    spacing: { before: opts.before ?? 60, after: opts.after ?? 60, line: 276 },
    children: parts.map((part) => run(part.text, part)),
  })
}

function h1(text) {
  return new Paragraph({
    heading: HeadingLevel.HEADING_1,
    spacing: { before: 360, after: 140 },
    border: { bottom: { color: ACCENT, space: 1, style: BorderStyle.SINGLE, size: 12 } },
    children: [run(text, { bold: true, size: 32, color: NAVY })],
  })
}

function h2(text) {
  return new Paragraph({
    heading: HeadingLevel.HEADING_2,
    spacing: { before: 260, after: 80 },
    children: [run(text, { bold: true, size: 26, color: ACCENT })],
  })
}

function bullet(text) {
  return new Paragraph({
    numbering: { reference: 'bullets', level: 0 },
    spacing: { before: 40, after: 40, line: 276 },
    children: [run(text)],
  })
}

function steps(items) {
  const reference = `steps-${stepCursor++}`
  return items.map(
    (text) =>
      new Paragraph({
        numbering: { reference, level: 0 },
        spacing: { before: 50, after: 50, line: 276 },
        children: [run(text)],
      })
  )
}

const manualDir = resolve(dirname(fileURLToPath(import.meta.url)), '../docs/meeting-manual')

function figure(file, caption, maxWidth = 640) {
  const data = readFileSync(resolve(manualDir, file))
  const width = data.readUInt32BE(16)
  const height = data.readUInt32BE(20)
  const w = Math.min(maxWidth, width)
  const h = Math.round((height * w) / width)
  return [
    new Paragraph({
      alignment: AlignmentType.CENTER,
      spacing: { before: 180, after: 40 },
      children: [
        new ImageRun({
          type: 'png',
          data,
          transformation: { width: w, height: h },
          altText: { title: caption, description: caption, name: file },
        }),
      ],
    }),
    new Paragraph({
      alignment: AlignmentType.CENTER,
      spacing: { before: 20, after: 160 },
      children: [run(caption, { size: 18, italics: true, color: MUTED })],
    }),
  ]
}

function note(text) {
  return new Paragraph({
    spacing: { before: 80, after: 80, line: 276 },
    shading: { fill: 'F7F1FB' },
    border: { left: { color: ACCENT, space: 8, style: BorderStyle.SINGLE, size: 16 } },
    children: [run(text, { size: 20, color: '3D2A4A' })],
  })
}

function cell(text, opts = {}) {
  return new TableCell({
    width: opts.width ? { size: opts.width, type: WidthType.DXA } : undefined,
    shading: { fill: opts.fill ?? 'FFFFFF' },
    margins: { top: 60, bottom: 60, left: 80, right: 80 },
    children: [
      new Paragraph({
        children: [run(text, { bold: opts.bold, size: opts.size ?? 20, color: opts.color ?? '1F2933' })],
      }),
    ],
  })
}

function table(headers, rows, widths) {
  const total = widths.reduce((s, n) => s + n, 0)
  return new Table({
    width: { size: total, type: WidthType.DXA },
    columnWidths: widths,
    rows: [
      new TableRow({
        tableHeader: true,
        children: headers.map((header, i) =>
          cell(header, { bold: true, fill: HEAD_BG, color: 'FFFFFF', width: widths[i], size: 20 })
        ),
      }),
      ...rows.map(
        (row, index) =>
          new TableRow({
            children: row.map((value, i) =>
              cell(value, { fill: index % 2 ? ALT_BG : 'FFFFFF', width: widths[i] })
            ),
          })
      ),
    ],
  })
}

function spacer() {
  return new Paragraph({ spacing: { before: 80, after: 80 }, children: [] })
}

